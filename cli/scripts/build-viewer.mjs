// Bundles the alignment pack viewer (src/viewer) into one JS and one CSS string
// and writes them to src/lib/alignment-viewer.generated.ts, so the renderer can
// inline the viewer into every pack and stay standalone with no network access.
//
// The generated module is committed: CI typechecks and tests without building,
// and the renderer imports it like any other source file.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const result = await build({
  entryPoints: ['src/viewer/main.tsx'],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  jsx: 'automatic',
  outdir: 'viewer-out',
  write: false,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
});

const output = ext => result.outputFiles.find(file => file.path.endsWith(ext)).text;
// A literal </script or </style inside inline code would end the element early.
const inline = (text, tag) => text.replaceAll(`</${tag}`, `<\\/${tag}`);

writeFileSync(
  'src/lib/alignment-viewer.generated.ts',
  `// Generated by scripts/build-viewer.mjs from src/viewer. Do not edit.
// Bundles React and React DOM (MIT), React Flow (MIT), Lucide (ISC), react-markdown (MIT) and elkjs (EPL-2.0); see THIRD_PARTY_NOTICES at the repo root.
export const VIEWER_JS = ${JSON.stringify(inline(output('.js'), 'script'))};
export const VIEWER_CSS = ${JSON.stringify(inline(output('.css'), 'style'))};
`
);
console.log('esbuild: built src/lib/alignment-viewer.generated.ts');
